# Track which chapter to write next
CHAPTER_COUNTER_FILE = os.path.expanduser("~/.cron-scheduler/data/chapter_counter.txt")
XIYOU_DIR = os.path.expanduser("~/Documents/qoder-workspace/x-agent/workspace/西游记后传")

def get_next_chapter_number():
    """Get the next chapter number to write"""
    if os.path.exists(CHAPTER_COUNTER_FILE):
        with open(CHAPTER_COUNTER_FILE, 'r') as f:
            try:
                counter = int(f.read().strip())
                return counter + 1
            except ValueError:
                return 1
    else:
        return 1

def save_chapter_number(chapter_num):
    """Save the current chapter number"""
    os.makedirs(os.path.dirname(CHAPTER_COUNTER_FILE), exist_ok=True)
    with open(CHAPTER_COUNTER_FILE, 'w') as f:
        f.write(str(chapter_num))

